import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const site = JSON.parse(readFileSync('data/site.json','utf8'));
assert.equal(site.siteUrl,'https://dailyledger.store');
const sitemap = readFileSync('dist/sitemap.xml','utf8');
const locations = [...sitemap.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => m[1]);
assert.equal(new Set(locations).size,locations.length);
assert(locations.every(url => new URL(url).origin === site.siteUrl),'Marketing sitemap has only its own host');
assert(!locations.some(url => /\/(404|thank-you)$/.test(url)));
const appSitemap = readFileSync('dist/app-sitemap.xml','utf8');
const accountLocations = [...appSitemap.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => m[1]);
assert.deepEqual(accountLocations,[site.loginUrl,site.signupUrl]);
assert(accountLocations.every(url => new URL(url).origin === new URL(site.appUrl).origin));
const rows = [];
const titles = new Set(), descriptions = new Set();
for (const file of readdirSync('dist').filter(file => file.endsWith('.html'))) {
  const html = readFileSync('dist/'+file,'utf8');
  const title = html.match(/<title>(.*?)<\/title>/)[1];
  const description = html.match(/<meta name="description" content="([^"]+)"/)[1];
  const canonical = html.match(/rel="canonical" href="([^"]+)"/)[1];
  const expected = site.siteUrl + (file === 'index.html' ? '/' : '/' + file.slice(0,-5));
  assert.equal(canonical,expected,`${file}: canonical URL`);
  assert.equal((html.match(/<title>/g)||[]).length,1,`${file}: one title`);
  assert.equal((html.match(/<meta name="description"/g)||[]).length,1,`${file}: one description`);
  assert(!titles.has(title) && title.length > 0 && title.length < 60,`${file}: title`);
  assert(!descriptions.has(description) && description.length > 0 && description.length < 160,`${file}: description`);
  titles.add(title); descriptions.add(description);
  assert(html.includes(`property="og:url" content="${canonical}"`),`${file}: Open Graph URL`);
  assert(html.includes(`property="og:description" content="${description}"`),`${file}: Open Graph description`);
  assert(html.includes(`name="twitter:description" content="${description}"`),`${file}: Twitter description`);
  assert(html.includes(`content="${site.siteUrl}/og-image.png"`),`${file}: social image domain`);
  const schemas = [...html.matchAll(/<script type="application\/ld\+json">(.*?)<\/script>/gs)].map(m => JSON.parse(m[1]));
  schemas.forEach(schema => assert.equal(schema['@context'],'https://schema.org'));
  const graph = schemas.find(schema => schema['@graph'])['@graph'];
  const webpage = graph.find(node => node['@id'] === canonical+'#webpage');
  assert.equal(webpage?.url,canonical);
  const organization = graph.find(node => node['@type'] === 'Organization');
  assert.equal(organization.name,site.businessName);
  assert.equal(organization.email,site.supportEmail);
  const indexable = !html.includes('content="noindex, follow"');
  assert.equal(locations.includes(canonical),indexable,`${file}: sitemap matches indexability`);
  rows.push(`| /${file === 'index.html' ? '' : file.slice(0,-5)} | ${title.replace(/\|/g,'\\|')} | ${description} | ${title.length} | ${description.length} | ${indexable ? 'Yes' : 'No'} | Valid JSON |`);
}
const robots = readFileSync('dist/robots.txt','utf8');
assert(robots.includes('Sitemap: '+site.siteUrl+'/sitemap.xml'));
const llms = readFileSync('dist/llms.txt','utf8');
assert(llms.includes(site.siteUrl) && llms.includes(site.loginUrl) && llms.includes(site.signupUrl) && llms.includes(site.supportEmail));
mkdirSync('docs',{recursive:true});
writeFileSync('docs/SEO-AUDIT.md',`# SEO validation\n\nCanonical domain: ${site.siteUrl}\n\n| Page | Title | Description | Title chars | Description chars | In sitemap | Schema |\n|---|---|---|---:|---:|---|---|\n${rows.join('\n')}\n\nAll canonical/social domains, title/description uniqueness and length checks, schema JSON and key entity fields, sitemap membership, robots.txt and llms.txt passed. This is local validation; Google indexing and rich-result eligibility require checks on the deployed site. Login/signup are external app account routes, not marketing authentication screens. Their real URLs are listed in app-sitemap.xml, which should be published on the app host.\n`);
console.log(`SEO checks passed for ${rows.length} pages, ${locations.length} marketing URLs, 2 account URLs, robots.txt and llms.txt.`);
